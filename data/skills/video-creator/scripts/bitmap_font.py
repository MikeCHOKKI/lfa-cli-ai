CHAR_W = 5
CHAR_H = 7
SPACING = 1  # pixels between characters


def text_width(text):
    return len(text) * (CHAR_W + SPACING) - SPACING


def draw_text(pixels, x, y, text, color, scale=1):
    """Draw text at (x, y). scale multiplies the 5x7 pixel size."""
    ox, oy = x, y
    for ch in text.upper():
        if ch not in FONT:
            continue
        glyph = FONT[ch]
        for row in range(CHAR_H):
            for col in range(CHAR_W):
                if glyph[row] & (1 << (CHAR_W - 1 - col)):
                    for sy in range(scale):
                        for sx in range(scale):
                            py = oy + row * scale + sy
                            px = ox + col * scale + sx
                            if 0 <= py < len(pixels) and 0 <= px < len(pixels[0]):
                                pixels[py][px] = color
        ox += (CHAR_W + SPACING) * scale
    return ox  # return end x position


def draw_text_centered(pixels, cx, y, text, color, scale=1):
    """Draw text centered at x=cx."""
    tw = text_width(text) * scale
    x = cx - tw // 2
    return draw_text(pixels, x, y, text, color, scale)
